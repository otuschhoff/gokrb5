// Package ntstatus provides Windows status codes returned in KERB-EXT-ERROR.
package ntstatus

import "fmt"

// Code is a 32-bit NTSTATUS value.
type Code uint32

// NTSTATUS codes carried in KERB-ERROR-DATA extended errors (MS-ERREF).
//
//revive:disable:var-naming Preserve published NTSTATUS identifiers.
const (
	// STATUS_NO_LOGON_SERVERS indicates that no logon servers are available to service the logon request.
	STATUS_NO_LOGON_SERVERS Code = 0xC000005E
	// STATUS_LOGON_FAILURE indicates the logon attempt failed due to invalid credentials.
	STATUS_LOGON_FAILURE          Code = 0xC000006D
	STATUS_ACCOUNT_RESTRICTION    Code = 0xC000006E
	STATUS_INVALID_LOGON_HOURS    Code = 0xC000006F
	STATUS_INVALID_WORKSTATION    Code = 0xC0000070
	STATUS_PASSWORD_EXPIRED       Code = 0xC0000071
	STATUS_ACCOUNT_DISABLED       Code = 0xC0000072
	STATUS_NOT_SUPPORTED          Code = 0xC00000BB
	STATUS_TIME_DIFFERENCE_AT_DC  Code = 0xC0000133
	STATUS_LOGON_TYPE_NOT_GRANTED Code = 0xC000015B
	STATUS_ACCOUNT_EXPIRED        Code = 0xC0000193
	STATUS_NOT_FOUND              Code = 0xC0000225
	STATUS_PASSWORD_MUST_CHANGE   Code = 0xC0000224
	STATUS_ACCOUNT_LOCKED_OUT     Code = 0xC0000234
	STATUS_NO_MATCH               Code = 0xC0000272
	STATUS_UNSUPPORTED_PREAUTH    Code = 0xC0000351
)

//revive:enable:var-naming

//nolint:gochecknoglobals // Static lookup table, read-only after initialization.
var statusNames = map[Code]string{
	STATUS_NO_LOGON_SERVERS:       "STATUS_NO_LOGON_SERVERS",
	STATUS_LOGON_FAILURE:          "STATUS_LOGON_FAILURE",
	STATUS_ACCOUNT_RESTRICTION:    "STATUS_ACCOUNT_RESTRICTION",
	STATUS_INVALID_LOGON_HOURS:    "STATUS_INVALID_LOGON_HOURS",
	STATUS_INVALID_WORKSTATION:    "STATUS_INVALID_WORKSTATION",
	STATUS_PASSWORD_EXPIRED:       "STATUS_PASSWORD_EXPIRED",
	STATUS_ACCOUNT_DISABLED:       "STATUS_ACCOUNT_DISABLED",
	STATUS_NOT_SUPPORTED:          "STATUS_NOT_SUPPORTED",
	STATUS_TIME_DIFFERENCE_AT_DC:  "STATUS_TIME_DIFFERENCE_AT_DC",
	STATUS_LOGON_TYPE_NOT_GRANTED: "STATUS_LOGON_TYPE_NOT_GRANTED",
	STATUS_ACCOUNT_EXPIRED:        "STATUS_ACCOUNT_EXPIRED",
	STATUS_NOT_FOUND:              "STATUS_NOT_FOUND",
	STATUS_PASSWORD_MUST_CHANGE:   "STATUS_PASSWORD_MUST_CHANGE",
	STATUS_ACCOUNT_LOCKED_OUT:     "STATUS_ACCOUNT_LOCKED_OUT",
	STATUS_NO_MATCH:               "STATUS_NO_MATCH",
	STATUS_UNSUPPORTED_PREAUTH:    "STATUS_UNSUPPORTED_PREAUTH",
}

func (c Code) String() string {
	if name, ok := statusNames[c]; ok {
		return name
	}
	return fmt.Sprintf("NTSTATUS(0x%08X)", uint32(c))
}
